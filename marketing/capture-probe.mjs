import { createRequire } from 'node:module';
const require = createRequire('C:/Projects/kaye/apps/web/package.json');
const { chromium } = require('playwright');
const out = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, locale: 'pt-PT', isMobile: true, hasTouch: true });
const p = await ctx.newPage();
await p.goto('https://kaye-indol.vercel.app/teste', { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
await p.getByRole('button', { name: 'Saltar' }).click();
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/f1.png` });
await p.getByRole('button',{name:'Começar'}).first().click();
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/f2.png` });
console.log(await p.locator('main').innerText());
console.log((await p.getByRole('button').allInnerTexts()).join(' | '));
console.log((await p.getByRole('radio').allInnerTexts()).join(' | '));
await b.close();
